class Array02 {
    public static void main(String[] args) {
        int[] arr = {10, 20, 30, 40, 50};

        System.out.println(arr[1]); // 20

        System.out.println("----------------------------"); 

        for (int i = 0; i < arr.length; i++) {
            System.out.println(arr[i]);
        }
    }
}